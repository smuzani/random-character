#!/usr/bin/env node
/**
 * Builds the self-contained roll-lab page for publishing as an artifact.
 *
 *   node lab/build.js [outfile]     # default lab/dist/rcg-roll-lab.html
 *
 * lab/index.html is the source of truth — it works as-is on the deployed site
 * (plain <script src> tags, no build step). This script inlines those scripts
 * into one file with zero external requests, which is what the artifact's CSP
 * requires. It also regenerates lab/engine-stamp.js, which BOTH builds load.
 */

"use strict";

const fs = require('fs');
const path = require('path');
const { engineStamp } = require('./engine-files');

const LAB = __dirname;

// Stamp the engine's content hash where both builds can read it. A seed only
// replays to the same character on the engine it was rolled against, so
// exports carry this and `lab/roll.js --replay` warns when the desk has moved
// on. A stale committed stamp is self-correcting: it won't match the current
// engine, which is exactly when the warning should fire.
const stamp = engineStamp();
fs.writeFileSync(path.join(LAB, 'engine-stamp.js'),
  '// Generated by lab/build.js — do not edit.\n' +
  'const ENGINE_STAMP = ' + JSON.stringify(stamp) + ';\n');

// The engine banks carry em-dashes and curly apostrophes inside their string
// literals. The published page has no <head> of its own to declare a charset,
// so escape every non-ASCII char to \uXXXX — correct under any encoding, and
// safe because all non-ASCII in the engine sits inside strings/comments.
const escapeNonAscii = (s) => s.replace(/[\u0080-\uFFFF]/g,
  c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));

const inlined = [];
const page = fs.readFileSync(path.join(LAB, 'index.html'), 'utf8')
  .replace(/<script src="([^"]+)"><\/script>\n?/g, function (_, src) {
    inlined.push(src);
    return '';
  })
  .replace('<script>', function () {
    const bundle = inlined
      .map(src => fs.readFileSync(path.resolve(LAB, src), 'utf8'))
      .join('\n;\n');
    return '<script>\n' + escapeNonAscii(bundle) + '\n';
  });

if (!inlined.length) {
  console.error('No <script src> tags found in lab/index.html — nothing inlined.');
  process.exit(1);
}

const out = process.argv[2] || path.join(LAB, 'dist', 'rcg-roll-lab.html');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, page);
console.log('wrote ' + out + ' (' + (page.length / 1024).toFixed(0) + ' KB, ' +
  inlined.length + ' scripts inlined, engine ' + stamp + ')');
